//! Music Organizer core library. The Tauri binary in `main.rs` is a thin wrapper around [`run`].

pub mod commands;
pub mod core;
pub mod db;
pub mod error;
pub mod logging;
pub mod net;
pub mod os;
pub mod platforms;
pub mod secrets;
pub mod state;
pub mod tools;

use crate::state::AppState;
use std::sync::Arc;
use tauri::Manager;
use tauri_specta::{Builder, ErrorHandlingMode, collect_commands};

/// Where the generated TypeScript bindings are written (contracts/ipc.md).
pub const BINDINGS_PATH: &str = "../src/lib/bindings.ts";

/// Every IPC command and event. TypeScript bindings are generated from this.
pub fn specta_builder() -> Builder<tauri::Wry> {
    Builder::<tauri::Wry>::new()
        .error_handling(ErrorHandlingMode::Throw)
        .commands(collect_commands![
            commands::settings::get_settings,
            commands::settings::update_settings,
            commands::library::list_watched_folders,
            commands::library::add_watched_folder,
        ])
}

pub fn export_bindings(builder: &Builder<tauri::Wry>) {
    builder
        .export(
            specta_typescript::Typescript::default().header(
                "// GENERATED by tauri-specta — do not edit.\n/* eslint-disable */\n// @ts-nocheck",
            ),
            BINDINGS_PATH,
        )
        .expect("failed to export TypeScript bindings");
}

pub fn run() {
    let builder = specta_builder();
    #[cfg(debug_assertions)]
    export_bindings(&builder);

    tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_opener::init())
        .plugin(tauri_plugin_shell::init())
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);
            let dirs = os::AppDirs::resolve(app.handle())?;
            let guard = logging::init(&dirs.logs);
            app.manage(guard);
            tracing::info!(version = env!("CARGO_PKG_VERSION"), "starting");

            let db = db::Db::open(&dirs.data.join("library.db"))?;
            let net = Arc::new(net::Net::new(net::RetryPolicy::default()));
            let tools: Arc<dyn tools::ToolRunner> = Arc::new(tools::fake::FakeToolRunner::new());
            let registry = Arc::new(platforms::Registry::new(Vec::new()));
            app.manage(AppState {
                db,
                net,
                tools,
                registry,
                dirs,
            });
            Ok(())
        })
        .run(tauri::generate_context!())
        .expect("error while running Music Organizer");
}

